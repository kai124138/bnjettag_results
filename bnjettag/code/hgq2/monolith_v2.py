#!/usr/bin/env python3
"""monolith-v2 — hybrid-strategy WHOLE-MODEL hls4ml emission (full-synthesis Route A/C).

One hls4ml project containing an ENTIRE binary transformer, where every WEIGHTED layer
(input_proj, Q/K/V/O ×L, fc1/fc2 ×L, head_fc1/head_fc2 — 6L+3 total) is re-expressed as
the v2/v3-proven per-shape recipe (pure ±1 weights → BRAM ROM, wide accumulator, CSD-2
affine, ReLU-SAT) at **Strategy=Resource**, COMPOSED inside one graph via PointwiseConv1D +
explicit head reshapes; the weightless attention einsums (QKᵀ, attn·V) and QSoftmax stay on
the native einsum path at **Latency** via per-layer strategy overrides. SubLN unchanged.

ARCHITECTURE-AGNOSTIC: `--config <name>` selects any configs/<name>.json; every dim comes
from cfg['arch'] (nothing is pinned to the flagship D256/H8/L8/FFN1024). Route A ran this on
the 6.4M-param flagship (verdict 2026-07-11: 27.9M IR, structure-dominated → Vitis
Unroll/Inline wall); Route C runs the SAME emitter on the deployable-scale configs.

Rationale (FULL-SYNTHESIS.md Route A): the failed 27M-IR monolith (convert_final, all einsum
at Latency) was weight-INLINING-dominated (~101 MB of inlined constant weight arrays); moving
the 6.4M ±1 weights to ROM (load_weights_from_txt) should collapse the design toward
structure-dominated so single-project Vitis synthesis becomes tractable.

Gates before ship (this driver):
  (1) full-model C-sim: hls4ml(monolith) vs keras(monolith) on real jets ≥ 0.997
      (same methodology as convert_final GATE-2; SAT + wide-accum historically give ~0.999),
      PLUS reported context: keras(monolith) vs the HGQ2 EXPORT and vs the QAT checkpoint.
  (2) project inspection: no big-shape Latency einsum-DENSE remains (weighted layers are
      PointwiseConv1D/Dense at Resource with weight ROMs), relu outputs AP_SAT, einsum/softmax
      at Latency — asserted here and dumped to the store.
Deliverable: hls_prj tarball + size indicator (generated bytes/lines vs v1) + store + manifest.
csynth is mulder-only (this ships the tarball + the mulder command).

Usage:
  export WANDB_API_KEY=$(cat bnjettag/wandb-api-key.txt)     # or --checkpoint for a local copy
  python monolith_v2.py --checkpoint bnjettag/models/final/w1a8-s3/model_best.keras
  python monolith_v2.py --config final-small-w1a8 --checkpoint <small model_best.keras>
"""
from __future__ import annotations

