import json
import os
import platform
import shutil
import sys
import time

import numpy as np

_HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, _HERE)

import convert_final as cf  # noqa: E402
import probes_final_v2 as pv2  # noqa: E402
from bnhgq2.config import cfg_hash, PROJECT_ROOT  # noqa: E402
from bnhgq2.monolith import (build_monolith_v2, latency_layer_names,  # noqa: E402
                             per_layer_configs, widen_conv_dense_accum)

def _v1_firmware(h, variant, seed, rf):
    """The v1 (all-einsum-Latency) convert_final project for THIS config/seed, if one was
    ever emitted — the size-comparison baseline. Resolves to the flagship's
    runs/9676418a/w1a8-s3/hls_prj_rf256/firmware exactly as the old constant did; for any
    other config the directory simply does not exist and the comparison is skipped."""
    return os.path.join(PROJECT_ROOT, "bnjettag", "results", "final", "runs", h,
                        f"{variant}-s{seed}", f"hls_prj_rf{rf}", "firmware")


def _sm(z):
    z = z.astype(np.float64); z = z - z.max(-1, keepdims=True); e = np.exp(z)
    return e / e.sum(-1, keepdims=True)


def _firmware_size(fw_dir):
    """Cheap size indicator: bytes+lines of the generated codegen (what Vitis compiles)
    and of the weight store (inlined vs ROM). Returns a dict."""
    def bl(paths):
        b = l = 0
        for p in paths:
            if os.path.isfile(p):
                d = open(p, "rb").read(); b += len(d); l += d.count(b"\n")
        return b, l
    top = [os.path.join(fw_dir, f) for f in
           ("myproject.cpp", "myproject.h", "defines.h", "parameters.h")]
    tb, tl = bl(top)
    mcpp = os.path.join(fw_dir, "myproject.cpp")
    mb, ml = bl([mcpp])
    wdir = os.path.join(fw_dir, "weights")
    wbytes = wfiles = 0
    if os.path.isdir(wdir):
        for f in os.listdir(wdir):
            fp = os.path.join(wdir, f)
            if os.path.isfile(fp):
                wbytes += os.path.getsize(fp); wfiles += 1
    return {"top_cpp_h_bytes": tb, "top_cpp_h_lines": tl,
            "myproject_cpp_bytes": mb, "myproject_cpp_lines": ml,
            "weights_bytes": wbytes, "weights_files": wfiles}


def run(config=pv2.FLAGSHIP_CONFIG, checkpoint=None, variant=None, seed=None, wandb_run=None,
        rf=None, n_csim=64, n_ctx=256, keep_project=True):
    variant, seed, wandb_run = pv2.resolve_source(config, variant, seed, wandb_run)
    cfg, exp, qat, binz, calib, pe, X, ckpt_rel = pv2.load_model(
        config, checkpoint=checkpoint, variant=variant, seed=seed, wandb_run=wandb_run)
    h = cfg_hash(cfg)
    A = cfg["arch"]
    L = A["n_layers"]
    rf = rf or cfg["hls"].get("rf", 256)     # final-w1a8.json ships rf=256 (the Route-A value)
    store = os.path.join(PROJECT_ROOT, "bnjettag", "results", "final", "runs", h, "monolith-v2")
    os.makedirs(store, exist_ok=True)
    print(f"=== monolith-v2  cfg={cfg['name']} [{h}] rf={rf}  run={wandb_run} ===\n"
          f"    arch  D{A['d_model']} H{A['n_heads']} L{L} FFN{A['ffn_dim']} "
          f"T{A['n_part']} F{A['n_feat']} C{A['n_classes']}", flush=True)

    # (build) the hybrid monolith + port
    mono, reg = build_monolith_v2(cfg, binz, calib, pe)
    print(f"[build] monolith params={mono.count_params():,}  "
          f"dense/pointwise={len(reg['dense'])} last-axis-affine={len(reg['affine'])} "
          f"flat-affine={len(reg['affine_flat'])}", flush=True)

    # (fidelity context) keras(monolith) vs the HGQ2 export + QAT on real jets
    ym = cf.predict(mono, X[:n_ctx]).reshape(n_ctx, -1)
    ye = cf.predict(exp, X[:n_ctx]).reshape(n_ctx, -1)
    yq = cf.predict(qat, X[:n_ctx]).reshape(n_ctx, -1)
    sm_m, sm_e, sm_q = _sm(ym), _sm(ye), _sm(yq)
    fidelity = {
        "n": n_ctx,
        "vs_export": {"corr_logits": float(np.corrcoef(ym.ravel(), ye.ravel())[0, 1]),
                      "corr_scores": float(np.corrcoef(sm_m.ravel(), sm_e.ravel())[0, 1]),
                      "argmax_agree": float((sm_m.argmax(1) == sm_e.argmax(1)).mean())},
        "vs_qat": {"corr_logits": float(np.corrcoef(ym.ravel(), yq.ravel())[0, 1]),
                   "corr_scores": float(np.corrcoef(sm_m.ravel(), sm_q.ravel())[0, 1]),
                   "argmax_agree": float((sm_m.argmax(1) == sm_q.argmax(1)).mean())},
        "note": ("keras↔keras reformulation fidelity. vs_export ~0.995 corr_scores / vs_qat "
                 "~0.96 mirror the flagship's OWN characterized export↔QAT gap (LEDGER GATE1 "
                 "w1a8-s3 corr_scores 0.9697); the reformulation increment is small (per-shape "
                 "block-iso corr 0.9999987) and accumulates only through the 8 sensitive "
                 "softmaxes. This is a keras-side context number, NOT the hardware C-sim gate."),
    }
    print(f"[fidelity] keras(mono) vs EXPORT corr_scores={fidelity['vs_export']['corr_scores']:.6f} "
          f"argmax={fidelity['vs_export']['argmax_agree']:.4f} | vs QAT "
          f"corr_scores={fidelity['vs_qat']['corr_scores']:.6f}", flush=True)

    # (convert) hybrid strategy: Resource default, einsum/softmax → Latency
    cf.patch_resource_einsum_check()
    from bnhgq2.convert import convert, pack_for_mulder
    lat = latency_layer_names(L)
    lcfg = per_layer_configs(cfg, binz, rf, lat)

    def post_parse(hm):
        nre = cf.fix_relu_saturation(hm)
        nwi = widen_conv_dense_accum(hm)
        post_parse._n = (nre, nwi)
    post_parse._n = (0, 0)

    out = os.path.join(store, f"hls_prj_rf{rf}")
    shutil.rmtree(out, ignore_errors=True)
    csim_X = X[:n_csim]
    keras_ref = cf.predict(mono, csim_X)
    rf_caps = {n_: c["ReuseFactor"] for n_, c in lcfg.items() if "ReuseFactor" in c}
    print(f"[convert] Strategy=Resource (weighted→BRAM) + {len(lat)} Latency overrides "
          f"(einsum/softmax); RF={rf}; pointwise RF caps={rf_caps}. Compiling C-sim "
          f"({n_csim} jets)…", flush=True)
    hm, report = convert(mono, cfg, out, rf=rf, strategy="Resource",
                         csim_X=csim_X, keras_ref=keras_ref,
                         post_parse=post_parse, layer_configs=lcfg)
    nre, nwi = post_parse._n
    cs = report.get("csim", {})
    g_pass = cs.get("corr", 0.0) >= 0.997
    print(f"[GATE C-sim] hls4ml(mono) vs keras(mono): corr={cs.get('corr')} "
          f"max|Δ|={cs.get('max_abs_diff')} bit_exact={cs.get('bit_exact')} "
          f"relu_sat={nre} wide_accum={nwi}  pass={g_pass}", flush=True)

    # (inspect) project structure — proves the redesign landed
    fw = os.path.join(out, "firmware")
    cls = {}
    for l_ in hm.get_layers():
        cls[l_.class_name] = cls.get(l_.class_name, 0) + 1
    mcpp = open(os.path.join(fw, "myproject.cpp")).read()
    defs = open(os.path.join(fw, "defines.h")).read()
    inspect = {
        "layer_class_census": cls,
        "nnet_pointwise_conv_calls": mcpp.count("nnet::pointwise_conv_1d"),
        "nnet_dense_calls": mcpp.count("nnet::dense<"),
        "nnet_einsum_dense_calls": mcpp.count("nnet::einsum_dense"),   # MUST be 0 (the win)
        "nnet_einsum_calls": mcpp.count("nnet::einsum<"),              # act×act, Latency
        "nnet_softmax_calls": mcpp.count("nnet::softmax"),
        "nnet_subln_calls": mcpp.count("nnet::subln"),
        "weight_roms_load_from_txt": mcpp.count("load_weights_from_txt"),
        "relu_outputs_AP_SAT": defs.count("AP_SAT") > 0,
        "einsum_at_latency": all(
            (l_.get_attr("strategy", "") or "").lower() == "latency"
            for l_ in hm.get_layers() if l_.class_name == "Einsum"),
        "weighted_at_resource": all(
            (l_.get_attr("strategy", "") or "").lower() == "resource"
            for l_ in hm.get_layers() if l_.class_name in ("PointwiseConv1D", "Dense")),
    }
    # Structural expectation DERIVED FROM cfg['arch'] — holds for any config, and reproduces
    # the flagship's documented L=8 inventory (49 pointwise / 2 dense / 16 einsum / 8 softmax
    # / 35 SubLN / 0 einsum_dense) exactly. A mismatch means the emission lost a layer.
    exp_inv = {"pointwise_conv": 1 + 6 * L, "dense": 2, "einsum": 2 * L,
               "softmax": L, "subln": 4 * L + 3, "einsum_dense": 0}
    got_inv = {"pointwise_conv": inspect["nnet_pointwise_conv_calls"],
               "dense": inspect["nnet_dense_calls"],
               "einsum": inspect["nnet_einsum_calls"],
               "softmax": inspect["nnet_softmax_calls"],
               "subln": inspect["nnet_subln_calls"],
               "einsum_dense": inspect["nnet_einsum_dense_calls"]}
    inspect["expected_from_arch"] = exp_inv
    inspect["structure_matches_arch"] = bool(got_inv == exp_inv)
    print(f"[inspect] pointwise={inspect['nnet_pointwise_conv_calls']} dense={inspect['nnet_dense_calls']} "
          f"einsum_DENSE={inspect['nnet_einsum_dense_calls']} (must=0) einsum(act×act)="
          f"{inspect['nnet_einsum_calls']} softmax={inspect['nnet_softmax_calls']} "
          f"weight_ROMs={inspect['weight_roms_load_from_txt']} relu_SAT={inspect['relu_outputs_AP_SAT']}",
          flush=True)
    print(f"[inspect] einsum@Latency={inspect['einsum_at_latency']} "
          f"weighted@Resource={inspect['weighted_at_resource']} "
          f"structure_matches_arch(L={L})={inspect['structure_matches_arch']} "
          f"expected={exp_inv}", flush=True)

    # (size indicator) generated bytes/lines vs the v1 (all-einsum-Latency) monolith
    v2_size = _firmware_size(fw)
    v1_fw = _v1_firmware(h, variant, seed, rf)
    v1_size = _firmware_size(v1_fw) if os.path.isdir(v1_fw) else None
    size = {"v2_monolith": v2_size, "v1_monolith": v1_size,
            "note": ("v1 = the failed all-einsum-Latency flagship convert (hash 9676418a; 27M-IR "
                     "OOM on mulder). The decisive delta is weights: v1 INLINES ±1 constant arrays "
                     "(weight-inlining-dominated); v2 stores them as ROM (load_weights_from_txt) so "
                     "clang LTO stays bounded — the numbers below quantify code+weight volume, the "
                     "ROM-vs-inline distinction is what un-blocks Vitis (mulder is the arbiter).")}
    if v1_size:
        print(f"[size] myproject.cpp  v1={v1_size['myproject_cpp_lines']}L/"
              f"{v1_size['myproject_cpp_bytes']}B  ->  v2={v2_size['myproject_cpp_lines']}L/"
              f"{v2_size['myproject_cpp_bytes']}B", flush=True)
        print(f"[size] weights dir    v1={v1_size['weights_bytes']/1e6:.1f}MB/"
              f"{v1_size['weights_files']}f  ->  v2={v2_size['weights_bytes']/1e6:.1f}MB/"
              f"{v2_size['weights_files']}f", flush=True)

    tar = pack_for_mulder(out, out + ".tar.gz")

    # (store)
    rec = {"written": time.strftime("%Y-%m-%dT%H:%M:%S"),
           "config": cfg["name"], "config_hash": h, "wandb_run": wandb_run,
           "variant": variant, "seed": seed, "arch": dict(A),
           "checkpoint": ckpt_rel, "rf": rf,
           "part": cfg["hls"].get("part"), "clock_ns": cfg["hls"].get("clock_ns"),
           "strategy": "Resource(weighted)+Latency(einsum/softmax)",
           "n_latency_overrides": len(lat), "pointwise_rf_caps": rf_caps,
           "post_parse": {"relu_sat_patched": nre, "wide_accum_widened": nwi},
           "csim_gate": {"n": cs.get("n"), "corr": cs.get("corr"),
                         "max_abs_diff": cs.get("max_abs_diff"),
                         "bit_exact": cs.get("bit_exact"), "threshold": 0.997,
                         "pass": bool(g_pass), "keras_ref": "keras(monolith-v2)"},
           "keras_reformulation_fidelity": fidelity,
           "project_inspection": inspect,
           "size_indicator": size,
           "tarball": os.path.relpath(tar, PROJECT_ROOT),
           "mulder_cmd": f"./mulder_csynth.sh {os.path.basename(tar)}"}
    with open(os.path.join(store, "monolith_v2_verify.json"), "w") as f:
        json.dump(rec, f, indent=1)
    if not keep_project:
        shutil.rmtree(out, ignore_errors=True)

    print(f"\n[done] monolith-v2: C-sim={'PASS' if g_pass else 'CHECK'} "
          f"einsum_DENSE_remaining={inspect['nnet_einsum_dense_calls']} "
          f"weight_ROMs={inspect['weight_roms_load_from_txt']}\n"
          f"       store   -> {os.path.relpath(store, PROJECT_ROOT)}\n"
          f"       tarball -> {os.path.relpath(tar, PROJECT_ROOT)}\n"
          f"       mulder  -> scp {os.path.relpath(tar, PROJECT_ROOT)} mulder:~/ ; "
          f"./mulder_csynth.sh {os.path.basename(tar)}", flush=True)
    return rec


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--config", default=pv2.FLAGSHIP_CONFIG,
                    help="config name in configs/ WITHOUT .json (default: the flagship "
                         "final-w1a8; e.g. final-small-w1a8). All dims come from its arch.")
    ap.add_argument("--checkpoint", default=None, help="local model_best.keras (skips W&B)")
    ap.add_argument("--variant", default=None, help="W&B checkpoint subdir stem "
                    "(default: config name minus 'final-')")
    ap.add_argument("--seed", type=int, default=None, help="default: 3 for the flagship, else 1")
    ap.add_argument("--wandb-run", default=None, help="default: <config>-s<seed>")
    ap.add_argument("--rf", type=int, default=None, help="default: cfg['hls']['rf']")
    ap.add_argument("--n-csim", type=int, default=64)
    ap.add_argument("--n-ctx", type=int, default=256)
    a = ap.parse_args()
    run(config=a.config, checkpoint=a.checkpoint, variant=a.variant, seed=a.seed,
        wandb_run=a.wandb_run, rf=a.rf, n_csim=a.n_csim, n_ctx=a.n_ctx)


if __name__ == "__main__":
    main()
